fn to_auth(body: AuthResponse) -> (String, AuthUser) {
    (body.token, body.record.into_auth())
}

/// PATCH body for role writes: the list plus the `is_admin` mirror that PB
/// rules must use for exact matching (JSON arrays only support substring `~`).
fn roles_payload(roles: &[String]) -> serde_json::Value {
    serde_json::json!({
        "roles": roles,
        "is_admin": roles.iter().any(|r| r == "admin"),
    })
}

