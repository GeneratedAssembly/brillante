    async fn auth_from_response(
        resp: reqwest::Response,
        reject_msg: &str,
    ) -> Result<(String, AuthUser), PbError> {
        let status = resp.status();
        if status == reqwest::StatusCode::BAD_REQUEST {
            return Err(PbError::Rejected(reject_msg.to_string()));
        }
        if status == reqwest::StatusCode::UNAUTHORIZED {
            return Err(PbError::Rejected(reject_msg.to_string()));
        }
        if !status.is_success() {
            return Err(PbError::Unreachable(format!("auth: {status}")));
        }
        let body: AuthResponse = resp
            .json()
            .await
            .map_err(|e| PbError::Unreachable(format!("auth decode: {e}")))?;
        Ok(to_auth(body))
    }
