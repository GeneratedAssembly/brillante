    /// Idempotently ensure each configured email holds the `admin` role.
    /// Only existing accounts are promoted; emails without an account are
    /// reported as missing rather than auto-created.
    pub async fn bootstrap_admins(
        &self,
        su_token: &str,
        emails: &[String],
    ) -> Result<BootstrapReport, PbError> {
        let mut report = BootstrapReport::default();
        for raw in emails {
            let email = raw.trim().to_lowercase();
            if email.is_empty() {
                continue;
            }
            let filter = format!("email = {}", filter_quote(&email));
            let users: Vec<AuthUser> = self
                .list_all(
                    "/api/collections/users/records",
                    Some(su_token),
                    &[("filter".into(), filter)],
                )
                .await?;
            match users.into_iter().next() {
                None => report.missing.push(email),
                Some(user) => {
                    if user.roles.iter().any(|r| r == "admin") {
                        report.already_admin.push(email);
                    } else {
                        let mut roles = user.roles.clone();
                        roles.push("admin".to_string());
                        self.update_user_roles(su_token, &user.id, &roles).await?;
                        report.promoted.push(email);
                    }
                }
            }
        }
        Ok(report)
    }

