use serde::Deserialize;

#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Deserialize)]
pub struct AuthUser {
    pub id: String,
    #[serde(default)]
    pub email: String,
    #[serde(default)]
    pub name: String,
    /// Free-form course-access roles assigned by admins; `admin` is the
    /// special value granting platform administration. Empty for plain users.
    #[serde(default, deserialize_with = "string_vec_lenient")]
    pub roles: Vec<String>,
    /// PocketBase record creation stamp ("YYYY-MM-DD HH:MM:SS.mmmZ"), empty
    /// when unavailable. Display code shows only the date part.
    #[serde(default)]
    pub created: String,
}

impl AuthUser {
    pub fn display(&self) -> String {
        if self.name.trim().is_empty() {
            self.email.clone()
        } else {
            self.name.clone()
        }
    }

    pub fn is_admin(&self) -> bool {
        self.roles.iter().any(|r| r == "admin")
    }
}

/// One OAuth2 provider enabled on the PocketBase `users` collection, as
/// reported by the public `auth-methods` endpoint. `state` and `code_verifier`
/// are pre-generated by PocketBase for this exact request: the state must be
/// verified against the provider's callback and the verifier must be sent
/// back with the code exchange (PKCE).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OAuthProvider {
    pub name: String,
    pub display_name: String,
    pub auth_url: String,
    pub state: String,
    pub code_verifier: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PbError {
    /// Credentials or submitted data were rejected. The string is safe to
    /// show: it is generic for auth failures (never leaks email existence).
    Rejected(String),
    /// The session token is invalid, expired, or revoked.
    Unauthorized,
    /// PocketBase could not be reached; the caller should degrade, not blame
    /// the user.
    Unreachable(String),
}

#[derive(Debug, Deserialize)]
struct AuthResponse {
    token: String,
    record: RecordJson,
}

#[derive(Debug, Deserialize)]
struct RecordJson {
    id: String,
    #[serde(default)]
    email: String,
    #[serde(default)]
    name: String,
    #[serde(default, deserialize_with = "string_vec_lenient")]
    roles: Vec<String>,
    #[serde(default)]
    created: Option<String>,
}

/// Decode a PB multi-value field tolerantly: JSON arrays (the supported
/// shape), legacy single strings (comma-separated), null, or missing all
/// yield a list instead of failing the whole record decode.
fn string_vec_lenient<'de, D>(deserializer: D) -> Result<Vec<String>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let value = Option::<serde_json::Value>::deserialize(deserializer)?;
    Ok(match value {
        Some(serde_json::Value::Array(items)) => items
            .into_iter()
            .filter_map(|v| v.as_str().map(str::to_string))
            .collect(),
        Some(serde_json::Value::String(s)) => s
            .split(',')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(str::to_string)
            .collect(),
        _ => Vec::new(),
    })
}

#[derive(Debug, Deserialize)]
struct ListResponse<T> {
    items: Vec<T>,
    #[serde(default, rename = "page")]
    page: u32,
    #[serde(default, rename = "totalPages")]
    total_pages: u32,
    #[serde(default, rename = "totalItems")]
    total_items: u32,
}

