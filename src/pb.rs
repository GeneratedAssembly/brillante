/// Turn a PB 400 body into a user-facing rejection with a generic fallback.
fn reject_message(body: &serde_json::Value, fallback: &str) -> PbError {
    let msg = body
        .get("message")
        .and_then(|m| m.as_str())
        .unwrap_or(fallback);
    PbError::Rejected(msg.to_string())
}

/// Extracts the enabled OAuth2 providers from an `auth-methods` response.
/// Tolerant to the legacy `authMethods` envelope; entries without an authURL
/// (misconfigured or disabled) are skipped rather than surfaced as buttons.
fn parse_auth_methods(body: &serde_json::Value) -> Vec<OAuthProvider> {
    let root = body.get("authMethods").unwrap_or(body);
    let Some(providers) = root
        .get("oauth2")
        .and_then(|o| o.get("providers"))
        .and_then(|p| p.as_array())
    else {
        return Vec::new();
    };
    providers
        .iter()
        .filter_map(|p| {
            let name = p.get("name")?.as_str()?.to_string();
            let auth_url = p
                .get("authURL")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string();
            if auth_url.is_empty() {
                return None;
            }
            let display_name = p
                .get("displayName")
                .and_then(|v| v.as_str())
                .filter(|s| !s.trim().is_empty())
                .unwrap_or(&name)
                .to_string();
            Some(OAuthProvider {
                name,
                display_name,
                auth_url,
                state: p
                    .get("state")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_string(),
                code_verifier: p
                    .get("codeVerifier")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_string(),
            })
        })
        .collect()
}

fn unreachable(e: reqwest::Error) -> PbError {
    PbError::Unreachable(format!("pocketbase unreachable: {e}"))
}

/// Escape a value for safe inlining into a PocketBase filter string literal.
/// The REST API has no server-side binding, so values are embedded as quoted
/// literals; double quotes and backslashes are escaped.
/// Filter selecting the user's notebook row(s) for a course, optionally a
/// single lesson. Callers must slug-validate the values first.
fn notebook_filter(user_id: &str, course: &str, lesson: Option<&str>) -> String {
    let mut filter = format!(
        "user = {} && course = {}",
        filter_quote(user_id),
        filter_quote(course)
    );
    if let Some(lesson) = lesson {
        filter.push_str(&format!(" && lesson = {}", filter_quote(lesson)));
    }
    filter
}

pub(crate) fn filter_quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        if ch == '"' || ch == '\\' {
            out.push('\\');
        }
        out.push(ch);
    }
    out.push('"');
    out
}

impl std::fmt::Display for PbError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PbError::Rejected(m) | PbError::Unreachable(m) => write!(f, "{m}"),
            PbError::Unauthorized => write!(f, "session expired"),
        }
    }
}

