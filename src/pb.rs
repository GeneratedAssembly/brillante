    fn parse_auth_methods_extracts_enabled_providers() {
        let body = serde_json::json!({
            "password": { "identityFields": ["email"], "enabled": true },
            "oauth2": {
                "enabled": true,
                "providers": [
                    provider_json("oidc", "Google", "https://tenant.auth0.com/authorize?connection=google-oauth2&state=pb_state_123&redirect_uri="),
                    provider_json("oidc2", "", ""), // no authURL: skipped
                ],
            },
            "mfa": { "enabled": false, "duration": 0 },
            "otp": { "enabled": false, "duration": 0 },
        });
        let providers = parse_auth_methods(&body);
        assert_eq!(providers.len(), 1);
        let p = &providers[0];
        assert_eq!(p.name, "oidc");
        assert_eq!(p.display_name, "Google");
        assert_eq!(p.state, "pb_state_123");
        assert_eq!(p.code_verifier, "verifier_abc");
        assert!(p.auth_url.ends_with("&redirect_uri="));
    }

